# English Phrase to Translation Key mapping for gettext-style fallback lookup
PHRASE_TO_KEY = {}
for _k, _v in TRANSLATIONS['en'].items():
    PHRASE_TO_KEY[_v.lower().strip()] = _k
    PHRASE_TO_KEY[_k.lower().strip()] = _k


def get_translation(phrase_or_key, lang='en', default=None, **kwargs):
    """
    Translates phrase_or_key into the target language lang ('en', 'hi', 'mr').
    Supports both translation keys (e.g. 'search_buses') and exact English phrases (e.g. 'Search Buses').
    Gracefully falls back to English, then default, then the key itself.
    """
    if not phrase_or_key:
        return ''

    lang = lang if lang in TRANSLATIONS else 'en'
    raw_str = str(phrase_or_key).strip()
    norm_str = raw_str.lower()

    # 1. Direct key match
    key = norm_str if norm_str in TRANSLATIONS['en'] else PHRASE_TO_KEY.get(norm_str)

    target_dict = TRANSLATIONS.get(lang, TRANSLATIONS['en'])

    if key and key in target_dict:
        res = target_dict[key]
    elif key and key in TRANSLATIONS['en']:
        res = TRANSLATIONS['en'][key]
    else:
        res = default if default is not None else raw_str

    if kwargs and isinstance(res, str):
        try:
            return res.format(**kwargs)
        except Exception:
            return res
    return res
